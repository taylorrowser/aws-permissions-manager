"""Configured WorkOS boundaries; constructing one never authorizes network use.

Tests inject httpx.MockTransport. Real dispatch needs BOTH allow_live=True and
an exact, operation-scoped InvocationApproval supplied by the trusted host.
The public AuthKit adapter has no API-key/client-secret parameter or env lookup.
No response/error body or token is logged. See WORKOS.md for the review limits.
"""
